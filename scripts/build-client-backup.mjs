import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
export function buildClientBackup(root=path.dirname(path.dirname(fileURLToPath(import.meta.url)))){
 const files=['migration.js','zip.js','client-backup-entry.js'];
 const source=files.map(file=>fs.readFileSync(path.join(root,'worker',file),'utf8').replace(/^export\s+(?=(?:async\s+)?(?:class|function|const)\b)/gm,''));
 fs.writeFileSync(path.join(root,'dist/client-backup-worker.js'),'// Generated by scripts/build-client-backup.mjs; private authenticated asset.\n'+source.join('\n'));
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))buildClientBackup();
